//
// ── この分類に固有の事情 ─────────────────────────
// 他の七分類と違い、この九項は**記録を作る側**である。
// 市政の記録・法廷の記録・徴税の台帳は、いずれも領が付けたものであり、
// 本書の他の項の典拠の多くが、この九つの宮廷から出ている。
// したがってこの分類では、「記録の欠落」が他の分類と違う意味を持つ。
// 記録を作る側が書かなかったことは、書けなかったのではなく、
// **書かないことを選んだ**可能性がある。両者を本書は区別できない。
// 区別できないことを、各項の欠落の欄に明記した。
//
// もう一つ。九領の「門戸」はすべて「試練による」になった。
// 揃ったのは記述の手抜きではない。この州では、首長の座は血によって継がれ、
// 宮廷に加わる道——従士（セイン）の位——は領への功によってのみ開く。
// 願い出て入る者はおらず、生まれで宮廷に入る者もいない。九領がこの一点で揃っている。

