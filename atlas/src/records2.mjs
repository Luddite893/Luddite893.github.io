// 第二版の記事本文　——　五節構成
//
// 改訂提案 一「解説文の拡充」への実装。
//
// ── 節を分ける理由 ────────────────────────────────
// 初版は一項を「概要」一本で書いていた。二百字の枠に
// 成立の経緯・内部の規律・外部の評価・分からなかったことを
// すべて詰めると、どれも一行ずつになり、結果として何も残らない。
// 節を分けるのは分量を増やすためではなく、**性質の違う記述を混ぜないため**である。
//
// ── 「評判」の書き方 ───────────────────────────────
// ここだけは他の節と規則が違う。
//   ・記録どうしが食い違う箇所は、**食い違ったまま並べる**
//   ・誰がそう呼んだかを必ず添える
//   ・本書はどちらが正しいかを書かない
// 序で「どちらの記録者も嘘は書いていない」と述べた方法論を、
// 本編に降ろすための欄である。矛盾を解消したら、この欄は死ぬ。
//
// ── 「記録の欠落」の書き方 ─────────────────────────
// 分からなかったことを書く。推測は書かない。
// 「〜と思われる」で埋めた瞬間、この欄も死ぬ。
// 書けるのは三種だけである。
//   一　存在するが閲覧できなかった記録
//   二　存在したが失われた記録
//   三　そもそも作られなかった記録
// 三のうちどれかを明示する。
//
// ── 沿革の年号 ──────────────────────────────────
// 沿革は年号つきの段落として持つ。年号は版面の外側の欄に立てる。
// 年表と同じ数字なので、年表からも本編からも同じ事件へ行ける。
//
// ── ファイルの分割 ────────────────────────────────
// 本文は四十九項で八万字に達するので、分類ごとのファイルに分けてある。
// ここは束ねるだけの層で、外から見た形（records2 / lengths / SPEC）は変えない。

import { cat1 } from './records2/cat1.mjs';
import { cat2 } from './records2/cat2.mjs';
import { cat3 } from './records2/cat3.mjs';
import { cat4 } from './records2/cat4.mjs';
import { cat5 } from './records2/cat5.mjs';
import { cat6 } from './records2/cat6.mjs';
import { cat7 } from './records2/cat7.mjs';

export const records2 = {
  ...cat1,
  ...cat2,
  ...cat3,
  ...cat4,
  ...cat5,
  ...cat6,
  ...cat7,
};

// 文字数の検査。仕様の枠に収まっているかを機械で見る。
export const lengths = (id) => {
  const r = records2[id];
  const n = (s) => [...String(s)].length;
  return {
    概要: n(r.summary),
    沿革: r.history.reduce((a, h) => a + n(h.text), 0),
    内情: r.inner.reduce((a, h) => a + n(h.text), 0),
    評判: r.repute.reduce((a, h) => a + n(h.text), 0),
    記録の欠落: n(r.gaps),
    関係の註: Math.max(0, ...Object.values(r.relNotes).map(n)),
  };
};

export const SPEC = {
  概要: [200, 250], 沿革: [400, 600], 内情: [300, 500],
  評判: [200, 300], 記録の欠落: [80, 150], 関係の註: [0, 40],
};

// 総字数。進捗の把握に使う。
export const total = () =>
  Object.keys(records2).reduce((a, id) => {
    const L = lengths(id);
    return a + L.概要 + L.沿革 + L.内情 + L.評判 + L.記録の欠落;
  }, 0);
